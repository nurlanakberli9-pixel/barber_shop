create table barbershop (
    id bigint generated by default as identity primary key,
    name varchar(255) not null,
    master_name varchar(255) not null,
    address varchar(255) not null,
    rating double precision not null,
    active boolean not null default true,
    constraint ck_barbershop_rating check (rating >= 0 and rating <= 5)
);

create table app_user (
    id bigint generated by default as identity primary key,
    username varchar(255) not null,
    password_hash varchar(255) not null,
    role varchar(255) not null,
    enabled boolean not null default true,
    barbershop_id bigint,
    constraint uq_app_user_username unique (username),
    constraint uq_app_user_barbershop unique (barbershop_id),
    constraint fk_app_user_barbershop foreign key (barbershop_id) references barbershop (id),
    constraint ck_app_user_role check (role in ('BARBER', 'ADMIN'))
);

create table service_type (
    id bigint generated by default as identity primary key,
    barbershop_id bigint not null,
    kind varchar(255) not null,
    single_minutes integer,
    low_minutes integer,
    medium_minutes integer,
    high_minutes integer,
    constraint uq_service_type unique (barbershop_id, kind),
    constraint fk_service_type_shop foreign key (barbershop_id) references barbershop (id),
    constraint ck_service_kind check (kind in ('HAIRCUT', 'WASH', 'BEARD')),
    constraint ck_service_single check (single_minutes is null or single_minutes between 5 and 240),
    constraint ck_service_low check (low_minutes is null or low_minutes between 5 and 240),
    constraint ck_service_medium check (medium_minutes is null or medium_minutes between 5 and 240),
    constraint ck_service_high check (high_minutes is null or high_minutes between 5 and 240),
    constraint ck_service_order check (low_minutes is null or medium_minutes is null or high_minutes is null
        or (low_minutes <= medium_minutes and medium_minutes <= high_minutes))
);

create table work_range (
    id bigint generated by default as identity primary key,
    barbershop_id bigint not null,
    start_minute integer not null,
    end_minute integer not null,
    constraint fk_work_range_shop foreign key (barbershop_id) references barbershop (id),
    constraint ck_work_range check (start_minute >= 0 and end_minute <= 1440 and start_minute < end_minute)
);
create index idx_work_range_shop on work_range (barbershop_id);

create table combo_buffer (
    id bigint generated by default as identity primary key,
    barbershop_id bigint not null,
    combo_key varchar(40) not null,
    after_minutes integer not null,
    constraint uq_combo_buffer unique (barbershop_id, combo_key),
    constraint fk_combo_buffer_shop foreign key (barbershop_id) references barbershop (id),
    constraint ck_combo_after check (after_minutes between 0 and 240)
);

create table booking (
    id bigint generated by default as identity primary key,
    barbershop_id bigint not null,
    booking_date date not null,
    start_minute integer not null,
    duration_minutes integer not null,
    buffer_minutes integer not null,
    services varchar(96) not null,
    customer_name varchar(60) not null,
    customer_phone varchar(16) not null,
    created_at timestamp(6) not null,
    constraint fk_booking_shop foreign key (barbershop_id) references barbershop (id),
    constraint ck_booking_time check (start_minute >= 0 and start_minute < 1440
        and duration_minutes > 0 and buffer_minutes >= 0)
);
create index idx_booking_shop_date on booking (barbershop_id, booking_date);
create index idx_booking_phone on booking (customer_phone, created_at);

create table closed_day (
    id bigint generated by default as identity primary key,
    barbershop_id bigint not null,
    closed_date date not null,
    constraint uq_closed_day unique (barbershop_id, closed_date),
    constraint fk_closed_day_shop foreign key (barbershop_id) references barbershop (id)
);

create table push_subscription (
    id bigint generated by default as identity primary key,
    barbershop_id bigint not null,
    endpoint varchar(600) not null,
    p256dh varchar(200) not null,
    auth varchar(100) not null,
    created_at timestamp(6) not null,
    constraint uq_push_endpoint unique (endpoint),
    constraint fk_push_shop foreign key (barbershop_id) references barbershop (id)
);
create index idx_push_shop on push_subscription (barbershop_id);
